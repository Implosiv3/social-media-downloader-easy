# ---------------------------------------------------------------------------
# JavaScript compatibility helpers
# ---------------------------------------------------------------------------

def _js_imul(
    a: int,
    b: int
) -> int:
    """
    Python equivalent of JavaScript Math.imul().
    """

    result = (a & 0xFFFFFFFF) * (b & 0xFFFFFFFF)
    result &= 0xFFFFFFFF

    if result >= 0x80000000:
        result -= 0x100000000

    return result


def _js_char_codes(
    value: str
):
    """
    JavaScript String.charCodeAt() works with UTF-16 code units,
    rather than Python Unicode code points.
    """

    encoded = value.encode('utf-16-le')

    for index in range(0, len(encoded), 2):
        yield int.from_bytes(
            encoded[index:index + 2],
            byteorder='little'
        )


def _browser_fingerprint_hash(
    value: str
) -> str:
    """
    Exact implementation of the `ne()` function used by ig.media.
    """

    R = 3735928559
    f = 1103547991

    for char_code in _js_char_codes(value):
        R = _js_imul(
            R ^ char_code,
            2654435761
        )

        f = _js_imul(
            f ^ char_code,
            1597334677
        )

    R = (
        _js_imul(
            R ^ ((R & 0xFFFFFFFF) >> 16),
            2246822507
        )
        ^
        _js_imul(
            f ^ ((f & 0xFFFFFFFF) >> 13),
            3266489909
        )
    )

    f = (
        _js_imul(
            f ^ ((f & 0xFFFFFFFF) >> 16),
            2246822507
        )
        ^
        _js_imul(
            R ^ ((R & 0xFFFFFFFF) >> 13),
            3266489909
        )
    )

    R_unsigned = R & 0xFFFFFFFF
    f_unsigned = f & 0xFFFFFFFF

    value_number = (
        4294967296 * (2097151 & f_unsigned)
        + R_unsigned
    )

    return format(
        value_number,
        'x'
    ).zfill(16)


def _generate_browser_fingerprint() -> str:
    """
    Recreates the browser fingerprint generated by ig.media.

    The original browser implementation uses:

        screen.width
        screen.height
        screen.colorDepth
        timezone offset
        navigator.platform
        navigator.language
        navigator.hardwareConcurrency
        canvas.toDataURL()

    The canvas rendering cannot be reproduced exactly from pure Python,
    so for now we reproduce the rest of the fingerprint and use the
    same hashing algorithm.
    """

    global _IGMEDIA_BROWSER_FP

    if _IGMEDIA_BROWSER_FP is not None:
        return _IGMEDIA_BROWSER_FP

    values = [
        '1920x1080x24',
        'tz:-480',
        'p:Win32',
        'l:en-US',
        'c:8'
    ]

    # The browser adds:
    #
    # cv:${canvas.toDataURL().slice(-32)}
    #
    # We intentionally leave it out for this first test.
    #
    # Once we know the server requires the exact canvas fingerprint,
    # we can obtain it from Chrome/Playwright and add it here.

    fingerprint_source = '|'.join(values)

    _IGMEDIA_BROWSER_FP = _browser_fingerprint_hash(
        fingerprint_source
    )

    return _IGMEDIA_BROWSER_FP


